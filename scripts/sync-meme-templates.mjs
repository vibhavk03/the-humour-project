import { readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const metadata = JSON.parse(await readFile(path.join(root, "app/trial/sample-metadata.json"), "utf8"));
const files = (await readdir(path.join(root, "memes"), { withFileTypes: true }))
  .filter(file => file.isFile() && /\.(png|jpe?g|webp|gif)$/i.test(file.name))
  .map(file => file.name);
// Keep curated ordering, with newly discovered files first.
const ordered = [...files.filter(file => !Object.hasOwn(metadata, file)).sort(), ...Object.keys(metadata).filter(file => files.includes(file))];
const mimeTypes = { jpeg: "image/jpeg", png: "image/png", webp: "image/webp", gif: "image/gif" };
const samples = [];
const ids = new Set();
for (const filename of ordered) {
  const bytes = await readFile(path.join(root, "memes", filename));
  if (!bytes.length || bytes.length > 5 * 1024 * 1024) {
    console.warn(`Skipping ${filename}: must be nonempty and 5 MB or smaller (${(bytes.length / 1024 / 1024).toFixed(2)} MB).`);
    continue;
  }
  let image;
  try { image = await sharp(bytes, { animated: true }).metadata(); }
  catch { console.warn(`Skipping ${filename}: unreadable image.`); continue; }
  if (!mimeTypes[image.format]) {
    console.warn(`Skipping ${filename}: unsupported image format.`);
    continue;
  }
  const stem = path.parse(filename).name;
  const curated = metadata[filename];
  const slug = stem.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48) || "sample";
  const id = curated?.id ?? `${slug}-${createHash("sha256").update(filename).digest("hex").slice(0, 8)}`;
  if (ids.has(id)) throw new Error(`Duplicate template ID: ${id}`);
  ids.add(id);
  const label = curated?.label ?? stem.replace(/[_-]+/g, " ");
  samples.push({ id, filename, label, description: curated?.description ?? `A meme template titled "${label}".`, animated: (image.pages ?? 1) > 1, mimeType: mimeTypes[image.format] });
}
if (!samples.length) throw new Error("No usable meme templates found.");
const output = `// Generated by npm run sync:memes. Edit sample-metadata.json for curated copy.\nexport type Sample = { id: string; filename: string; label: string; description: string; animated: boolean; mimeType: string };\n\n// Explicit allowlist: request paths and URLs never select arbitrary files.\nexport const SAMPLES: Sample[] = ${JSON.stringify(samples, null, 2)};\n\nexport function getSample(id: unknown) {\n  return typeof id === "string" ? SAMPLES.find(sample => sample.id === id) : undefined;\n}\n`;
const target = path.join(root, "app/trial/samples.ts");
if (await readFile(target, "utf8").catch(() => "") !== output) await writeFile(target, output);
console.log(`Synced ${samples.length} meme templates for the guest and Generate galleries.`);
